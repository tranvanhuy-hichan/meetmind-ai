"""Ports: the contracts between the core and the outside world.

Adapters live in `adapters/`; the core never imports them.
"""
from __future__ import annotations

from typing import Any, AsyncIterator, Protocol

from core.models import (
    Document,
    EmailMessage,
    Invitation,
    LoginCode,
    Meeting,
    MeetingEvent,
    Minutes,
    MinutesRecord,
    OrgMember,
    Organization,
    Participant,
    ProcessedDocument,
    Segment,
    Translation,
    User,
    VerifiedIdentity,
)


class MeetingBot(Protocol):
    """Joins a meeting on an external platform and reports what is said."""

    async def join(self, meeting_id: str, meet_url: str) -> None: ...

    async def leave(self, meeting_id: str) -> None: ...

    def segments(self, meeting_id: str) -> AsyncIterator[Segment]:
        """Live transcript segments. Finishes when the meeting is over."""
        ...

    def events(self, meeting_id: str) -> AsyncIterator[MeetingEvent]: ...

    async def get_recording(self, meeting_id: str) -> str | None:
        """Local path of the recording after the meeting, if available."""
        ...


class ASR(Protocol):
    async def transcribe_file(self, path: str, lang: str | None = None) -> list[Segment]: ...


class Translator(Protocol):
    async def translate(
        self,
        segments: list[Segment],
        target_lang: str,
        context: list[Segment] | None = None,
        glossary: dict[str, str] | None = None,
    ) -> list[Translation]: ...


class LLM(Protocol):
    async def complete_json(self, prompt_id: str, variables: dict[str, Any], schema: dict) -> dict: ...

    async def complete_text(self, prompt_id: str, variables: dict[str, Any]) -> str: ...


class IdentityVerifier(Protocol):
    async def verify(self, credential: str) -> VerifiedIdentity:
        """Checks a credential from the identity provider; raises Invalid if it is not acceptable."""
        ...


class MeetRooms(Protocol):
    def authorize_url(self, state: str) -> str: ...

    async def create_room(self, code: str) -> str:
        """Exchanges the authorization code and creates a room. Returns its meeting URL."""
        ...


class EmailSender(Protocol):
    async def send(self, message: EmailMessage) -> None: ...


class ObjectStore(Protocol):
    async def ensure_ready(self) -> None: ...

    async def put(self, key: str, data: bytes) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...


class DocumentProcessor(Protocol):
    """Turns an uploaded file into a PDF and counts its pages."""

    async def process(self, filename: str, data: bytes) -> ProcessedDocument: ...


class Subscription(Protocol):
    async def get(self) -> dict: ...

    def close(self) -> None: ...


class EventBus(Protocol):
    async def publish(self, topic: str, payload: dict) -> None: ...

    def subscribe(self, topic: str) -> Subscription: ...


class MinutesExporter(Protocol):
    content_type: str
    extension: str

    def export(self, meeting: Meeting, minutes: Minutes, participants: list[Participant]) -> bytes: ...


class Repository(Protocol):
    # users and sign-in
    async def create_user(self, email: str, name: str) -> User: ...
    async def get_user(self, user_id: str) -> User | None: ...
    async def get_user_by_email(self, email: str) -> User | None: ...
    async def update_user(self, user_id: str, **fields: Any) -> None: ...
    async def save_login_code(self, code: LoginCode) -> None: ...
    async def get_login_code(self, email: str) -> LoginCode | None: ...
    async def bump_login_attempts(self, email: str) -> None: ...
    async def delete_login_code(self, email: str) -> None: ...
    # organizations
    async def create_org(self, name: str, owner_id: str) -> Organization: ...
    async def get_org(self, org_id: str) -> Organization | None: ...
    async def update_org(self, org_id: str, **fields: Any) -> None: ...
    async def list_orgs_for_user(self, user_id: str) -> list[tuple[Organization, str]]: ...
    async def add_org_member(self, org_id: str, user_id: str, role: str) -> None: ...
    async def get_org_member(self, org_id: str, user_id: str) -> OrgMember | None: ...
    async def list_org_members(self, org_id: str) -> list[OrgMember]: ...
    async def update_org_member(self, org_id: str, user_id: str, role: str) -> None: ...
    async def remove_org_member(self, org_id: str, user_id: str) -> None: ...
    # invitations
    async def add_invitation(self, inv: Invitation) -> Invitation: ...
    async def get_invitation(self, inv_id: str) -> Invitation | None: ...
    async def list_invitations(self, org_id: str) -> list[Invitation]: ...
    async def find_invitations(self, email: str) -> list[Invitation]: ...
    async def mark_invitation_accepted(self, inv_id: str) -> None: ...
    async def delete_invitation(self, inv_id: str) -> None: ...
    # meetings
    async def create_meeting(self, org_id: str, owner_id: str, title: str, meet_url: str | None, scheduled_at, platform: str = "meet") -> Meeting: ...
    async def get_meeting(self, meeting_id: str) -> Meeting | None: ...
    async def get_meeting_by_code(self, code: str) -> Meeting | None: ...
    async def list_meetings_for_user(self, user_id: str) -> list[tuple[Meeting, str]]: ...
    async def list_meetings_by_status(self, statuses: list[str]) -> list[Meeting]: ...
    async def update_meeting(self, meeting_id: str, **fields: Any) -> None: ...
    # participants
    async def add_participant(self, meeting_id: str, user_id: str, role: str, display_lang: str | None) -> Participant: ...
    async def get_participant(self, meeting_id: str, user_id: str) -> Participant | None: ...
    async def list_participants(self, meeting_id: str) -> list[Participant]: ...
    async def update_participant(self, meeting_id: str, user_id: str, **fields: Any) -> None: ...
    # documents
    async def add_document(self, doc: Document) -> Document: ...
    async def get_document(self, doc_id: str) -> Document | None: ...
    async def list_documents(self, meeting_id: str) -> list[Document]: ...
    async def update_document(self, doc_id: str, **fields: Any) -> None: ...
    async def delete_document(self, doc_id: str) -> None: ...
    # transcript
    async def add_segment(self, seg: Segment) -> None: ...
    async def list_segments(self, meeting_id: str) -> list[Segment]: ...
    async def save_translation(self, tr: Translation) -> None: ...
    async def list_translations(self, meeting_id: str, lang: str) -> dict[str, Translation]: ...
    # minutes
    async def get_minutes(self, meeting_id: str) -> MinutesRecord | None: ...
    async def save_minutes(self, meeting_id: str, minutes: Minutes, status: str) -> MinutesRecord: ...
